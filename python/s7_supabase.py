from supabase import create_client

url = "ここに自分のProject URLを入れる"
key = "ここに自分のanon keyを入れる"

supabase = create_client(url, key)
print("接続しました")

res = supabase.table("items").select("*").execute()
print(res.data)

for row in res.data:
    print(row["title"], "/", row["category"])

items = supabase.table("items").select("id").execute().data
